def add(a: float, b: float) -> float:
    return a + b

def factorial(n: int) -> int:
    return n * factorial(n-1) if n > 1 else 1
def subtract(a: float, b: float) -> float:
    return a - b

def multiply(a: float, b: float) -> float:
    return a * b

def power(a: float, b: int) -> float:
    return a ** b
